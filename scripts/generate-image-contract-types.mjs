#!/usr/bin/env node
/** Generate P0 image contract types. Runtime decoding remains a separate validation step. */
import { readFileSync, writeFileSync } from 'node:fs';
import { format, resolveConfig } from 'prettier';

const root = new URL('../', import.meta.url);
const read = (file) => JSON.parse(readFileSync(new URL(file, root), 'utf8'));
const live = read('contracts/rest/live-image-api.json');
const media = read('contracts/rest/device-media-api.json');
const alarm = read('contracts/rest/admin-alarm-api.json');
const base = read('contracts/rest/openapi-base.json');
const schemas = {
  ...base.components.schemas,
  ...live.components.schemas,
  ...media.components.schemas,
  EvidenceImage: alarm.components.schemas.EvidenceImage,
  Alarm: alarm.components.schemas.Alarm,
  DeviceEvent: alarm.components.schemas.DeviceEvent,
};

function typeOf(schema) {
  if (schema.$ref) return schema.$ref.split('/').at(-1);
  if (schema.const !== undefined) return JSON.stringify(schema.const);
  if (schema.enum) return schema.enum.map((value) => JSON.stringify(value)).join(' | ');
  if (schema.oneOf) return schema.oneOf.map(typeOf).join(' | ');
  if (Array.isArray(schema.type)) return schema.type.map((type) => typeOf({ ...schema, type })).join(' | ');
  if (schema.type === 'array') return `ReadonlyArray<${typeOf(schema.items ?? {})}>`;
  if (schema.type === 'object') {
    const fields = Object.entries(schema.properties ?? {}).map(
      ([key, value]) =>
        `  readonly ${JSON.stringify(key)}${schema.required?.includes(key) ? '' : '?'}: ${typeOf(value)};`,
    );
    return `{\n${fields.join('\n')}\n}`;
  }
  if (schema.type === 'integer' || schema.type === 'number') return 'number';
  return ['string', 'boolean', 'null'].includes(schema.type) ? schema.type : 'unknown';
}

const lines = ['// Generated by scripts/generate-image-contract-types.mjs. Do not edit.'];
for (const [name, schema] of Object.entries(schemas)) {
  let type = typeOf(schema);
  if (name === 'MediaUploadSessionCreate') {
    const condition = schema.allOf[0];
    if (condition.if.required.join() !== 'triggerRef' || condition.then.properties.mediaType.const !== 'IMAGE') {
      throw new Error('Review changed triggerRef condition before generating types');
    }
    type += ' & ({ readonly mediaType: "IMAGE" } | { readonly mediaType: "VIDEO"; readonly triggerRef?: never })';
  }
  lines.push(`export type ${name} = ${type};`);
}
const output = await format(lines.join('\n\n'), {
  ...(await resolveConfig('contracts/rest/image-types.ts')),
  parser: 'typescript',
});
const file = new URL('contracts/rest/image-types.ts', root);
if (process.argv.includes('--check')) {
  if (readFileSync(file, 'utf8') !== output) throw new Error('Regenerate image-types.ts');
} else writeFileSync(file, output);
